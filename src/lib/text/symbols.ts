export const symbols: SymbolEntry[] = symbolGroups.flatMap((group) =>
  entries[group].map((entry) => {
    const [glyph, name] = entry.split("|");
    return {
      glyph,
      name,
      group,
      code: `U+${glyph.codePointAt(0)!.toString(16).toUpperCase().padStart(4, "0")}`,
    };
  }),
);
export function findSymbols(query: string, group?: SymbolGroup): SymbolEntry[] {
  const q = query.trim().toLowerCase();
  return symbols.filter(
    (entry) =>
      (!group || entry.group === group) &&
      (!q ||
        `${entry.glyph} ${entry.name} ${entry.code}`.toLowerCase().includes(q)),
  );
}
