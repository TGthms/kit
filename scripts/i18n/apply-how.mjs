const moreFiles = ["how-copy-rest.json", "how-copy-rest2.json", "how-copy-rest3.json", "how-copy-rest4.json"];
const more = Object.assign(
  {},
  ...moreFiles.map((name) => JSON.parse(fs.readFileSync(path.join(root, "scripts/i18n", name), "utf8"))),
);

function apply(locale, patch) {
  const file = path.join(root, "messages", `${locale}.json`);
  const catalog = JSON.parse(fs.readFileSync(file, "utf8"));
  catalog.footer.how = patch.footerHow;
  catalog.settings.viewHow = patch.viewHow;
  catalog.settings.privacyNote = patch.privacyNote;
  catalog.how = patch.how;
  fs.writeFileSync(file, `${JSON.stringify(catalog, null, 2)}\n`);
  console.log(`updated ${locale}`);
}

for (const [locale, patch] of Object.entries(COPY)) apply(locale, patch);
for (const [locale, raw] of Object.entries(more)) apply(locale, pack(raw));
