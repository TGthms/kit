def main() -> None:
    missing = []
    for locale, overlay in COPY.items():
        path = MESSAGES / f"{locale}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        merge(data["home"], overlay)
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    zh_hans = json.loads((MESSAGES / "zh-Hans.json").read_text(encoding="utf-8"))
    (MESSAGES / "zh.json").write_text(json.dumps(zh_hans, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    expected = set(COPY)
    catalogs = {p.stem for p in MESSAGES.glob("*.json")} - {"en", "zh"}
    missing = sorted(catalogs - expected)
    extra = sorted(expected - catalogs)
    if missing or extra:
        raise SystemExit(f"locale mismatch missing={missing} extra={extra}")
    print(f"updated {len(COPY)} locales + zh alias")


if __name__ == "__main__":
    main()








